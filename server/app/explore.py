"""Explore globe: one shared archive story per (country, year, month, category).

The first request for a combination gathers candidates from all eight publishers and asks the AI to choose
the best one. The choice is stored, and every later reader of the same combination gets the stored row.

Candidates come from three places, merged and de-duplicated by normalized URL:
  1. The Guardian Open Platform archive search (needs GUARDIAN_API_KEY).
  2. Internet Archive Wayback Machine captures of the other seven publishers' RSS feeds (see wayback.py).
  3. Articles this server collected itself, when the month overlaps the rolling news window.
Each source reports its own status; one failing source never hides the others' candidates.

Past months are stored permanently. The current month is refreshed after 24 hours because new articles
are still being published, and so is a pick made while one of the sources was failing or not configured.
Failures (no candidates because a source was down, AI unavailable) are never stored, so a later request
can retry; a short in-memory cooldown stops a failing combination from hammering the providers.

Archive picks are a separate dataset from the rolling 7-day news window (see README "Retention").
"""
import calendar
import json
import re
import threading
from datetime import datetime, timedelta, timezone

import httpx
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from . import countries, guardian, wayback
from .analysis import _sanitize
from .config import PROMPTS_DIR, Settings
from .feeds import normalize_url
from .gemini import AIError, GeminiClient
from .models import Article, ExplorePick
from .timeutil import iso, utcnow
from .views import cutoff_for, live_stories_for_country

EARLIEST = (1999, 1)
CURRENT_MONTH_TTL = timedelta(hours=24)
INCOMPLETE_SOURCES_TTL = timedelta(hours=24)
FAILURE_COOLDOWN = timedelta(minutes=10)
MAX_PROMPT_CANDIDATES = 60
MAX_TRAIL_CHARS = 400
GUARDIAN_NAME = "The Guardian"
ATTRIBUTION = (
    "Archive sources: The Guardian Open Platform, and Internet Archive Wayback Machine captures of the "
    "BBC News, NPR, Fox News, CBS News, New York Times, Al Jazeera and ABC News RSS feeds."
)
AI_LABEL = "AI-generated"
AI_DISCLOSURE = (
    "The choice of story and the short intro were generated by an AI model using only each candidate's "
    "headline and the publisher's own summary where available, not the full article. Open the article to "
    "read the original reporting."
)
ARCHIVE_NOTE = (
    "Archive picks come from publisher archives and are kept as a separate, permanent cache. They are "
    "not part of the 7-day news window used by the Latest tab. Archive coverage varies by publisher and month."
)
CURRENT_MONTH_NOTE = "This month is still in progress, so its pick is refreshed every 24 hours."

VIA_GUARDIAN = "Guardian Open Platform archive search"
VIA_WAYBACK = "Wayback Machine RSS archive"
VIA_LOCAL = "My News collection (last 7 days)"

EXPLORE_SCHEMA = {
    "type": "OBJECT",
    "properties": {
        "status": {"type": "STRING", "enum": ["picked", "none_suitable"]},
        "choice": {"type": "STRING"},
        "reason": {"type": "STRING"},
        "intro": {"type": "STRING"},
    },
    "required": ["status", "choice", "reason", "intro"],
}

CATEGORIES: dict[str, dict] = json.loads((PROMPTS_DIR / "explore_categories.json").read_text(encoding="utf-8"))

_generation_lock = threading.Lock()  # one archive search + AI pick at a time (provider rate limits)
_failures: dict[tuple, tuple[datetime, dict]] = {}
_failures_lock = threading.Lock()


class ExploreInputError(ValueError):
    pass


def validate(country: str, year: int, month: int, category: str | None, now: datetime) -> tuple[dict, str, dict]:
    code = (country or "").strip().upper()
    info = countries.get_country(code)
    if info is None:
        raise ExploreInputError(f"unknown country code '{country}'")
    cat_id = (category or "all").strip().lower()
    if cat_id not in CATEGORIES:
        raise ExploreInputError(f"unknown category '{category}'; use one of {', '.join(CATEGORIES)}")
    if not 1 <= month <= 12:
        raise ExploreInputError("month must be between 1 and 12")
    if (year, month) < EARLIEST:
        raise ExploreInputError("the archive starts in January 1999")
    if (year, month) > (now.year, now.month):
        raise ExploreInputError("that month is in the future")
    return {"code": code, **info}, cat_id, CATEGORIES[cat_id]


def _month_label(year: int, month: int) -> str:
    return f"{calendar.month_name[month]} {year}"


def _month_bounds(year: int, month: int) -> tuple[datetime, datetime]:
    start = datetime(year, month, 1, tzinfo=timezone.utc)
    end = datetime(year + (month == 12), month % 12 + 1, 1, tzinfo=timezone.utc)
    return start, end


def _messages(status: str, country: dict, cat: dict, year: int, month: int) -> str | None:
    when = _month_label(year, month)
    return {
        "ok": None,
        "no_match": f"None of the archive articles about {country['name']} from {when} fit the "
        f"'{cat['label']}' filter.",
        "no_candidates": f"The publishers' archives available to My News have no matching articles about "
        f"{country['name']} for {when}.",
        "relevance_fallback": "The AI picker is unavailable right now, so this is the top archive search "
        "result. It has not been checked by AI.",
        "ai_unavailable": f"The AI picker is unavailable right now and the '{cat['label']}' filter needs it. "
        "Please try again later.",
        "source_unavailable": "The news archives could not be reached. Please try again later.",
    }.get(status)


def _base_payload(country: dict, cat_id: str, cat: dict, year: int, month: int, now: datetime) -> dict:
    return {
        "country": {"code": country["code"], "name": country["name"]},
        "year": year,
        "month": month,
        "month_label": _month_label(year, month),
        "category": {"id": cat_id, "label": cat["label"]},
        "is_current_month": (year, month) == (now.year, now.month),
        "status": None,
        "message": None,
        "pick": None,
        "ai": None,
        "cached": False,
        "generated_at": None,
        "expires_at": None,
        "candidates_considered": 0,
        "sources": [],
        "attribution": ATTRIBUTION,
        "archive_note": ARCHIVE_NOTE,
        "live_stories": [],
    }


def _pick_json(row_or_cand) -> dict:
    r = row_or_cand
    return {
        "headline": r.headline,
        "trail_text": r.trail_text or "",
        "url": r.url,
        "thumbnail": r.thumbnail,
        "section": r.section or None,
        "publisher": getattr(r, "publisher", None) or GUARDIAN_NAME,
        "published_at": iso(r.published_at),
        "source_id": getattr(r, "source_id", None) or getattr(r, "id", None),
    }


def _row_payload(row: ExplorePick, base: dict, country: dict, cat: dict, cached: bool) -> dict:
    out = dict(base)
    out.update(
        status=row.status,
        message=_messages(row.status, country, cat, row.year, row.month),
        cached=cached,
        generated_at=iso(row.generated_at),
        expires_at=iso(row.expires_at),
        candidates_considered=row.candidates_count,
        sources=row.sources or [],
    )
    if row.status == "ok":
        out["pick"] = _pick_json(row)
    if row.ai_reason:
        out["ai"] = {
            "label": AI_LABEL,
            "reason": row.ai_reason,
            "intro": row.ai_intro or None,
            "model": row.model,
            "prompt_version": row.prompt_version,
            "generated_at": iso(row.generated_at),
            "disclosure": AI_DISCLOSURE,
        }
    return out


def _cached_row(session: Session, key: tuple, now: datetime) -> ExplorePick | None:
    code, year, month, cat_id = key
    row = session.scalars(
        select(ExplorePick).where(
            ExplorePick.country == code,
            ExplorePick.year == year,
            ExplorePick.month == month,
            ExplorePick.category == cat_id,
        )
    ).one_or_none()
    return row


def _fresh(row: ExplorePick | None, now: datetime) -> bool:
    return row is not None and (row.expires_at is None or row.expires_at > now)


def _source(publisher: str, via: str, status: str, detail: str | None = None, found: int = 0) -> dict:
    return {"publisher": publisher, "via": via, "status": status, "detail": detail, "candidates": found}


def _guardian_candidates(http, settings, country, cat, year, month, now) -> tuple[list, dict, str]:
    if not settings.guardian_api_key:
        return [], _source(GUARDIAN_NAME, VIA_GUARDIAN, "not_configured", "GUARDIAN_API_KEY is not set"), ""
    try:
        found, query = guardian.find_candidates(http, settings.guardian_api_key, country, cat, year, month, now)
    except guardian.GuardianError as exc:
        return [], _source(GUARDIAN_NAME, VIA_GUARDIAN, "unavailable", str(exc)), ""
    return found, _source(GUARDIAN_NAME, VIA_GUARDIAN, "ok", found=len(found)), query


def _wayback_candidates(http, country, year, month, now) -> tuple[list, list[dict]]:
    results = wayback.fetch_month(http, list(wayback.ARCHIVED_FEEDS), year, month, now)
    cands, sources = [], []
    for pid, r in results.items():
        name = wayback.PUBLISHER_NAMES[pid]
        mine = [
            guardian.Candidate(
                id=normalize_url(it.url), url=it.url, headline=it.title, trail_text=it.excerpt or "",
                thumbnail=None, section="", published_at=it.published_at, publisher=name,
            )
            for it in r.items
            if it.title and countries.mentions(f"{it.title}\n{it.excerpt or ''}", country["code"])
        ]
        cands += mine
        sources.append(_source(name, VIA_WAYBACK, r.status, r.detail, len(mine)))
    return cands, sources


def _local_candidates(session, settings, country, year, month, now) -> tuple[list, dict | None]:
    start, end = _month_bounds(year, month)
    since = max(start, cutoff_for(now, settings.retention_hours))
    if since >= end:  # the month lies entirely before the rolling window
        return [], None
    rows = session.scalars(
        select(Article).where(Article.published_at >= since, Article.published_at < end)
        .order_by(Article.published_at.desc())
    ).all()
    cands = [
        guardian.Candidate(
            id=a.id, url=a.url, headline=a.title, trail_text=a.excerpt or "", thumbnail=None, section="",
            published_at=a.published_at, publisher=a.publisher_name,
        )
        for a in rows
        if countries.mentions(f"{a.title}\n{a.excerpt or ''}", country["code"])
    ]
    return cands, _source("All publishers", VIA_LOCAL, "ok", found=len(cands))


def gather_candidates(session, settings, http, country, cat, year, month, now) -> tuple[list, list[dict], str]:
    """All candidates from every source, de-duplicated by normalized URL, plus a status per source."""
    g_cands, g_source, g_query = _guardian_candidates(http, settings, country, cat, year, month, now)
    w_cands, w_sources = _wayback_candidates(http, country, year, month, now)
    l_cands, l_source = _local_candidates(session, settings, country, year, month, now)
    sources = [g_source, *w_sources] + ([l_source] if l_source else [])

    seen, merged = set(), []
    for c in g_cands + l_cands + w_cands:
        key = normalize_url(c.url)
        if key not in seen:
            seen.add(key)
            merged.append(c)
    query = "; ".join(
        p for p in (
            f"guardian: {g_query}" if g_query else "",
            f"wayback: {len(w_cands)} matching feed items",
            f"local: {len(l_cands)} matching articles" if l_source else "",
        ) if p
    )
    return merged, sources, query


def _order_candidates(
    cands: list[guardian.Candidate], code: str, keywords: list[str] | None = None
) -> list[guardian.Candidate]:
    """Candidates naming the country first, taken in turn from each publisher so none dominates the list.

    Within a publisher the source order is kept (for The Guardian that is its relevance ranking), except that
    candidates matching the category keywords come before those that do not.
    """
    named = [c for c in cands if countries.mentions(f"{c.headline}\n{c.trail_text}", code)]
    rest = [c for c in cands if c not in named]
    if keywords:
        pattern = re.compile(r"\b(?:" + "|".join(re.escape(k) for k in keywords) + ")", re.IGNORECASE)
        named.sort(key=lambda c: not pattern.search(f"{c.headline}\n{c.trail_text}"))
    queues: dict[str, list] = {}
    for c in named:
        queues.setdefault(c.publisher, []).append(c)
    interleaved = []
    while any(queues.values()):
        for q in queues.values():
            if q:
                interleaved.append(q.pop(0))
    return (interleaved + rest)[:MAX_PROMPT_CANDIDATES]


def build_user_text(country: dict, cat: dict, year: int, month: int, cands: list[guardian.Candidate]) -> str:
    lines = [
        f"Requested country: {country['name']} (ISO code {country['code']})",
        f"Requested month: {_month_label(year, month)}",
        f"Category: {cat['label']}. Category rule: {cat['rule']}",
        "Each candidate below is: code, publisher, section, publication time (UTC), headline, summary.",
        "<<<CANDIDATES_BEGIN>>>",
    ]
    for i, c in enumerate(cands, start=1):
        trail = _sanitize(c.trail_text or "")[:MAX_TRAIL_CHARS] or "(no summary)"
        lines.append(
            f"[C{i}] publisher: {_sanitize(c.publisher)} | section: {_sanitize(c.section) or 'unknown'} | "
            f"published: {iso(c.published_at) or 'unknown'}\n"
            f"headline: {_sanitize(c.headline)}\nsummary: {trail}"
        )
    lines.append("<<<CANDIDATES_END>>>")
    return "\n\n".join(lines)


def _ask_ai(session, ai, settings: Settings, key, country, cat, year, month, cands) -> dict:
    cfg = settings.model_config
    prompt = (PROMPTS_DIR / cfg["explore_prompt_file"]).read_text(encoding="utf-8")
    raw = ai.generate_json(
        session,
        purpose="explore_pick",
        ref="-".join(str(k) for k in key),
        system_prompt=prompt,
        user_text=build_user_text(country, cat, year, month, cands),
        schema=EXPLORE_SCHEMA,
        daily_cap=settings.ai_daily_limit,
    )
    status = raw.get("status")
    reason = (raw.get("reason") or "").strip() if isinstance(raw.get("reason"), str) else ""
    intro = (raw.get("intro") or "").strip() if isinstance(raw.get("intro"), str) else ""
    if status == "none_suitable":
        if not reason:
            raise AIError("none_suitable without a reason")
        return {"status": "no_match", "reason": reason}
    if status != "picked":
        raise AIError(f"unexpected status {status!r}")
    choice = (raw.get("choice") or "").strip().strip("[]").upper() if isinstance(raw.get("choice"), str) else ""
    if not choice.startswith("C") or not choice[1:].isdigit() or not 1 <= int(choice[1:]) <= len(cands):
        raise AIError(f"invalid candidate code {raw.get('choice')!r}")
    if not reason:
        raise AIError("picked without a reason")
    return {"status": "ok", "candidate": cands[int(choice[1:]) - 1], "reason": reason, "intro": intro}


def _store(session: Session, key: tuple, values: dict) -> ExplorePick:
    code, year, month, cat_id = key
    row = _cached_row(session, key, values["generated_at"])
    if row is None:
        row = ExplorePick(country=code, year=year, month=month, category=cat_id)
        session.add(row)
    for k, v in values.items():
        setattr(row, k, v)
    try:
        session.commit()
    except IntegrityError:  # another process stored the same combination first: use theirs
        session.rollback()
        row = _cached_row(session, key, values["generated_at"])
    return row


def _remember_failure(key: tuple, now: datetime, payload: dict) -> None:
    with _failures_lock:
        if len(_failures) > 1000:
            _failures.clear()
        _failures[key] = (now, payload)


def _recent_failure(key: tuple, now: datetime) -> dict | None:
    with _failures_lock:
        hit = _failures.get(key)
        if hit and now - hit[0] < FAILURE_COOLDOWN:
            return hit[1]
        _failures.pop(key, None)
    return None


def reset_failures() -> None:
    with _failures_lock:
        _failures.clear()


def _fallback_candidate(cands: list[guardian.Candidate], cat_id: str, cat: dict) -> guardian.Candidate | None:
    """The top search result, only when the search itself guarantees the category (no AI judgement needed)."""
    if cat_id == "all":
        return cands[0]
    if cat.get("guardian_section"):
        return next((c for c in cands if c.category_enforced), None)
    return None


def _generate(session, settings, ai, http, key, country, cat_id, cat, year, month, now, base) -> dict:
    """Gather candidates and pick a story. Returns the payload; stores it only when it is shareable."""
    found, sources, query = gather_candidates(session, settings, http, country, cat, year, month, now)
    base = {**base, "sources": sources}
    failed = any(s["status"] == "unavailable" for s in sources)
    incomplete = failed or any(s["status"] == "not_configured" for s in sources)
    if not found and failed:  # the missing source may have had the story: retry later, store nothing
        return {**base, "status": "source_unavailable", "message": _messages("source_unavailable", country, cat, year, month)}

    expires = now + CURRENT_MONTH_TTL if base["is_current_month"] else None
    if incomplete:
        expires = min(e for e in (expires, now + INCOMPLETE_SOURCES_TTL) if e is not None)
    common = {
        "generated_at": now, "expires_at": expires, "query": query[:1000], "candidates_count": len(found),
        "sources": sources,
    }
    clear = {
        "source_id": None, "url": None, "headline": None, "trail_text": None, "thumbnail": None,
        "section": None, "publisher": None, "published_at": None, "ai_reason": None, "ai_intro": None,
        "model": None, "prompt_version": None,
    }
    if not found:
        row = _store(session, key, {**clear, **common, "status": "no_candidates"})
        return _row_payload(row, base, country, cat, cached=False)

    cands = _order_candidates(found, country["code"], cat.get("keywords"))
    try:
        if not ai.configured:
            raise AIError("GEMINI_API_KEY is not configured")
        decision = _ask_ai(session, ai, settings, key, country, cat, year, month, cands)
    except Exception:  # provider, validation or unexpected errors: answer honestly, store nothing
        session.rollback()
        top = _fallback_candidate(cands, cat_id, cat)
        if top is not None:
            return {
                **base,
                "status": "relevance_fallback",
                "message": _messages("relevance_fallback", country, cat, year, month),
                "pick": _pick_json(top),
                "candidates_considered": len(found),
                "generated_at": iso(now),
            }
        return {**base, "status": "ai_unavailable", "message": _messages("ai_unavailable", country, cat, year, month)}

    ai_meta = {"model": ai.last_model, "prompt_version": settings.model_config["explore_prompt_version"]}
    if decision["status"] == "no_match":
        row = _store(session, key, {**clear, **common, **ai_meta, "status": "no_match", "ai_reason": decision["reason"]})
        return _row_payload(row, base, country, cat, cached=False)
    c = decision["candidate"]
    values = {
        **common,
        **ai_meta,
        "status": "ok",
        "source_id": c.id,
        "url": c.url,
        "headline": c.headline,
        "trail_text": c.trail_text,
        "thumbnail": c.thumbnail,
        "section": c.section or None,
        "publisher": c.publisher,
        "published_at": c.published_at,
        "ai_reason": decision["reason"],
        "ai_intro": decision["intro"] or None,
    }
    row = _store(session, key, values)
    return _row_payload(row, base, country, cat, cached=False)


def get_explore(
    session_factory,
    settings: Settings,
    country: str,
    year: int,
    month: int,
    category: str | None = "all",
    *,
    http: httpx.Client | None = None,
    ai: GeminiClient | None = None,
    now: datetime | None = None,
) -> dict:
    now = now or utcnow()
    info, cat_id, cat = validate(country, year, month, category, now)
    key = (info["code"], year, month, cat_id)
    base = _base_payload(info, cat_id, cat, year, month, now)
    if base["is_current_month"]:
        base["archive_note"] = f"{ARCHIVE_NOTE} {CURRENT_MONTH_NOTE}"
        with session_factory() as session:
            base["live_stories"] = live_stories_for_country(
                session, info["code"], cutoff_for(now, settings.retention_hours)
            )

    with session_factory() as session:
        row = _cached_row(session, key, now)
        if _fresh(row, now):
            return _row_payload(row, base, info, cat, cached=True)

    failed = _recent_failure(key, now)
    if failed is not None:
        return {**failed, "live_stories": base["live_stories"]}

    own_http = http is None
    http = http or httpx.Client(timeout=20.0, headers={"User-Agent": settings.user_agent})
    ai = ai or GeminiClient(settings)
    try:
        with _generation_lock:
            with session_factory() as session:
                row = _cached_row(session, key, now)  # someone may have generated it while we waited
                if _fresh(row, now):
                    return _row_payload(row, base, info, cat, cached=True)
                payload = _generate(session, settings, ai, http, key, info, cat_id, cat, year, month, now, base)
    finally:
        if own_http:
            http.close()
    if payload["status"] in ("source_unavailable", "ai_unavailable", "relevance_fallback"):
        _remember_failure(key, now, payload)
    return payload
